// Writes core/src/commonMain/kotlin/fold/core/ChartGlyphs.kt from the planner's symbol table (web/site/chart.js), so
// the apps draw the same symbols the planner prints. Run after changing GLYPHS: node web/tools/chart-glyphs-kt.mjs
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
const root = new URL("../../", import.meta.url);
const ctx = {}; vm.createContext(ctx); ctx.globalThis = ctx;
vm.runInContext(readFileSync(new URL("web/site/chart.js", root), "utf8"), ctx);
const G = ctx.RoadbookChart.GLYPHS;
const kq = s => JSON.stringify(s).replace(/\$/g, "\\$");
const rows = G.map(([id, name, group, els]) => `        G(${kq(id)}, ${kq(name)}, ${kq(group)}, listOf(${els.map(kq).join(", ")})),`).join("\n");
const kt = `package fold.core

// GENERATED by web/tools/chart-glyphs-kt.mjs from web/site/chart.js — do not edit by hand.

/**
 * The roll chart's symbols, the same table the planner prints from: each an original drawing in a 10 × 10 box.
 * p = stroked path, f = filled path, c = stroked circle, C = filled circle, t = bold text (x, y, size, words[:colour]).
 */
object ChartGlyphs {
    class G(val id: String, val name: String, val group: String, val els: List<String>)
    val all: List<G> = listOf(
${rows}
    )
    private val byId = all.associateBy { it.id }
    fun get(id: String): G? = byId[id]
    /** words in a glyph (CP, STOP, L1…): drawn by the app in bold at (x, y), size in the same units */
    class Words(val x: Double, val y: Double, val size: Double, val text: String, val light: Boolean)
    /** The glyph's shapes in a square of [size] with its top left at (x, y); words come separately, see [words]. */
    fun shapes(id: String, x: Double, y: Double, size: Double): List<Chart.Shape> {
        val g = byId[id] ?: return emptyList(); val k = size / 10; val w = maxOf(0.18, 0.8 * k); val out = ArrayList<Chart.Shape>()
        for (el in g.els) {
            val kind = el[0]; val body = el.substring(2)
            when (kind) {
                'p' -> out.add(Chart.PathShape(path(body, k, x, y), w, "ink", false, null))
                'f' -> out.add(Chart.PathShape(path(body, k, x, y), 0.0, "ink", true, null))
                'c', 'C' -> { val n = body.trim().split(Regex("\\\\s+")).map { it.toDouble() }; out.add(Chart.Circle(x + n[0] * k, y + n[1] * k, n[2] * k, if (kind == 'c') w else 0.0, "ink", kind == 'C')) }
            }
        }
        return out
    }
    fun words(id: String, x: Double, y: Double, size: Double): List<Words> {
        val g = byId[id] ?: return emptyList(); val k = size / 10
        return g.els.filter { it[0] == 't' }.mapNotNull { el ->
            val m = Regex("^(\\\\S+) (\\\\S+) (\\\\S+) ([^:]+)(?::(#[0-9a-fA-F]{6}))?$").find(el.substring(2)) ?: return@mapNotNull null
            Words(x + m.groupValues[1].toDouble() * k, y + m.groupValues[2].toDouble() * k, m.groupValues[3].toDouble() * k, m.groupValues[4], m.groupValues[5].isNotEmpty())
        }
    }
    private fun path(d: String, k: Double, x: Double, y: Double): List<DoubleArray> {
        val tok = Regex("[MLCZ]|-?\\\\d*\\\\.?\\\\d+").findAll(d).map { it.value }.toList(); val ops = ArrayList<DoubleArray>(); var i = 0
        while (i < tok.size) {
            val c = tok[i++]
            if (c == "Z") { ops.add(doubleArrayOf(3.0)); continue }
            val n = if (c == "C") 6 else 2; val a = DoubleArray(n + 1); a[0] = when (c) { "M" -> 0.0; "L" -> 1.0; else -> 2.0 }
            for (j in 0 until n) { val v = tok[i++].toDouble(); a[j + 1] = if (j % 2 == 1) y + v * k else x + v * k }
            ops.add(a)
        }
        return ops
    }
}
`;
writeFileSync(new URL("core/src/commonMain/kotlin/fold/core/ChartGlyphs.kt", root), kt);
console.log(`wrote ${G.length} glyphs`);
